class ReviewSubmissionRequest(BaseModel):
    """Request submitted by a human operator to approve or reject a recommendation."""
    recommendation_id: str = Field(description="ID of recommendation to approve or reject")
    decision: str = Field(description="'APPROVED' or 'REJECTED'")
    review_notes: str = Field(description="Operator technical rationale or justification")

    @field_validator("review_notes")
    @classmethod
    def validate_non_whitespace_notes(cls, v: str) -> str:
        trimmed = (v or "").strip()
        if not trimmed:
            raise ValueError("Reviewer notes cannot be empty or whitespace-only.")
        return trimmed


